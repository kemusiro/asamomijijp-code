// 12 MHz carrier oscillator -> 48 MHz control/USB. Not the ULX3S 25 MHz XO.
// PFD=12 MHz, VCO=576 MHz, CLKOP=48 MHz. Static, no dynamic PLL changes.
module revc_ulx3s_clocking(input wire ref12,reset,output wire clk,locked);
 wire feedback;
 (* FREQUENCY_PIN_CLKI="12", FREQUENCY_PIN_CLKOP="48",
    ICP_CURRENT="12", LPF_RESISTOR="8", MFG_ENABLE_FILTEROPAMP="1", MFG_GMCREF_SEL="2" *)
 EHXPLLL #(.PLLRST_ENA("ENABLED"),.INTFB_WAKE("DISABLED"),
  .STDBY_ENABLE("DISABLED"),.DPHASE_SOURCE("DISABLED"),
  .OUTDIVIDER_MUXA("DIVA"),.OUTDIVIDER_MUXB("DIVB"),
  .OUTDIVIDER_MUXC("DIVC"),.OUTDIVIDER_MUXD("DIVD"),
  .CLKI_DIV(1),.CLKFB_DIV(4),.CLKOP_ENABLE("ENABLED"),.CLKOP_DIV(12),
  .CLKOP_CPHASE(5),.CLKOP_FPHASE(0),.FEEDBK_PATH("INT_OP")) pll (
  .CLKI(ref12),.CLKFB(feedback),.CLKINTFB(feedback),.CLKOP(clk),.LOCK(locked),.RST(reset),
  .STDBY(1'b0),.PHASESEL0(1'b0),.PHASESEL1(1'b0),.PHASEDIR(1'b1),
  .PHASESTEP(1'b1),.PHASELOADREG(1'b1),.PLLWAKESYNC(1'b0),
  .ENCLKOP(1'b0),.ENCLKOS(1'b0),.ENCLKOS2(1'b0),.ENCLKOS3(1'b0));
endmodule
