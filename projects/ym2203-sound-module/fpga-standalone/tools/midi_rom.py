"""Generate fixed-4MHz MIDI ROM directly from the project's accepted C tables."""
import argparse,hashlib,re
from pathlib import Path

def render(project):
    p=Path(project)/'firmware-c/src/midi_pitch.h';raw=p.read_bytes();text=raw.decode();tables={}
    for name in ['midi_high','midi_low','midi_period']:
        m=re.search(name+r'\[128\]=\{(.*?)\};',text,re.S);tables[name]=[int(x) for x in re.findall(r'\d+',m[1])]
        if len(tables[name])!=128:raise ValueError('Expected 128 pitches')
    lines=['// SPDX-License-Identifier: MIT','// Generated by tools/midi_rom.py; fixed 4MHz.',
        '// Source midi_pitch.h SHA256 '+hashlib.sha256(raw).hexdigest(),
        'module revc_midi_rom(input wire [2:0] voice,input wire [6:0] note,',
        '    output reg valid,output reg [7:0] first,second);',
        '    reg [16:0] fm,ssg;', '    always @* begin','        fm=0;ssg=0;case(note)']
    for n in range(128):
        high=tables['midi_high'][n];low=tables['midi_low'][n];p=tables['midi_period'][n]
        lines.append(f"            7'd{n}:begin fm=17'h{((int(high!=255)<<16)|(high<<8)|low):05x};ssg=17'h{((int(p!=0)<<16)|((p&255)<<8)|(p>>8)):05x};end")
    lines+=['        endcase','        valid=voice<6&&(voice<3 ? fm[16] : ssg[16]);',
        '        first=voice<3 ? fm[15:8] : ssg[15:8];second=voice<3 ? fm[7:0] : ssg[7:0];','    end','endmodule','']
    return '\n'.join(lines)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--project',type=Path,default=Path(__file__).resolve().parents[2]);p.add_argument('--rtl',type=Path,required=True);a=p.parse_args();a.rtl.write_text(render(a.project))
