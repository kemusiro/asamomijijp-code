"""AN619 equations, exact integer-Hz plans; no third-party register-map code."""
from fractions import Fraction
from pathlib import Path
import argparse,json
DEFAULT=[4000000,3579545,3993600,3000000,2000000,1500000,2500000,3500000]


def parameters(ratio):
    a=ratio.numerator//ratio.denominator;b=ratio.numerator%ratio.denominator;c=ratio.denominator
    if c>1048575:raise ValueError('Fraction exceeds Si5351 denominator')
    q=128*b//c;p1=128*a+q-512;p2=128*b-c*q
    if not 0<=p1<262144:raise ValueError('P1 overflow')
    return [c>>8&255,c&255,p1>>16&3,p1>>8&255,p1&255,(c>>12&240)|(p2>>16&15),p2>>8&255,p2&255]


def decode(data):
    p1=((data[2]&3)<<16)|(data[3]<<8)|data[4]
    p2=((data[5]&15)<<16)|(data[6]<<8)|data[7]
    p3=((data[5]&240)<<12)|(data[0]<<8)|data[1]
    return Fraction(p1+512,128)+Fraction(p2,128*p3)


def plan(hz,xtal=25000000,load=10):
    if not 1500000<=hz<=4000000:raise ValueError('Validated design envelope: 1.5..4MHz')
    if xtal not in (25000000,27000000) or load not in (6,8,10):raise ValueError('Unsupported crystal')
    # Multiples of 50 keep feedback denominators within 20 bits for integer Hz.
    choices=[d for d in range(50,2049,50) if 600000000<=hz*d<=900000000]
    divider=min(choices,key=lambda d:abs(hz*d-800000000));vco=hz*divider
    a=Fraction(49152000*16,xtal);b=Fraction(vco,xtal)
    assert 15<=a<=90 and 15<=b<=90
    # address,value,write mask; reset is self-clearing and excluded from readback.
    rows=[(3,255,255),*[(r,128,255) for r in range(16,24)],(2,0xf8,0xf8),
          (9,255,255),(15,0,12),(24,0,255),(25,0,255),
          (183,{6:0x52,8:0x92,10:0xd2}[load],255),(149,0,128)]
    for addr,ratio in [(26,a),(34,b),(42,Fraction(divider)),(50,Fraction(16))]:
        rows.extend((addr+i,v,255) for i,v in enumerate(parameters(ratio)))
    rows.extend([(165,0,127),(166,0,127),(16,0x6c,255),(17,0x4c,255),(177,0xa0,0xa0)])
    assert decode(parameters(a))*xtal/16==49152000
    assert decode(parameters(b))*xtal/divider==hz
    return {'ym_hz':hz,'audio_hz':49152000,'xtal_hz':xtal,'load_pf':load,'plla_hz':786432000,
            'pllb_hz':vco,'ms0_divider':divider,'rows':rows,'src_num':hz,'src_den':3456000}


def render(profiles=DEFAULT,xtal=25000000,load=10):
    if len(profiles)!=8 or profiles[0]!=4000000:raise ValueError('Eight profiles; profile0 must remain 4MHz')
    plans=[plan(h,xtal,load) for h in profiles];size=len(plans[0]['rows'])
    lines=['// SPDX-License-Identifier: MIT','// Generated by tools/si5351_profiles.py; do not edit.',
           'module revc_si5351_rom(input wire [2:0] profile,input wire [6:0] index,',
           '    output reg [23:0] row,output reg [23:0] frequency,output wire [6:0] count);',
           f"    assign count=7'd{size};",'    always @* begin','        frequency=0;row=0;', '        case(profile)']
    for i,p in enumerate(plans):lines.append(f"            3'd{i}: frequency=24'd{p['ym_hz']};")
    lines.extend(['        endcase','        case({profile,index})'])
    for i,p in enumerate(plans):
        for j,(r,v,m) in enumerate(p['rows']):lines.append(f"            10'd{i*128+j}: row=24'h{r:02x}{v:02x}{m:02x};")
    lines.extend(['            default:row=0;','        endcase','    end','endmodule',''])
    return '\n'.join(lines),plans


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--rtl',type=Path,required=True);p.add_argument('--json',type=Path)
    p.add_argument('--xtal',type=int,default=25000000);p.add_argument('--load-pf',type=int,default=10)
    p.add_argument('--frequencies',type=int,nargs=8,default=DEFAULT);a=p.parse_args()
    rtl,plans=render(a.frequencies,a.xtal,a.load_pf);a.rtl.write_text(rtl)
    if a.json:a.json.write_text(json.dumps(plans,indent=2)+'\n')
