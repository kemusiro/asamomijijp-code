"""Generate the F1 CDC ACM + MIDI 1.0 descriptor ROM from numeric USB fields."""
import argparse,json
from pathlib import Path

def descriptors():
    config=[9,2,175,0,4,1,0,0xc0,1,
        8,11,0,2,2,2,1,4,
        9,4,0,0,1,2,2,1,4,
        5,0x24,0,0x10,1,
        5,0x24,1,0,1,
        4,0x24,2,2,
        5,0x24,6,0,1,
        7,5,0x81,3,8,0,16,
        9,4,1,0,2,10,0,0,0,
        7,5,2,2,64,0,0,7,5,0x82,2,64,0,0,
        8,11,2,2,1,0,0,5,
        9,4,2,0,0,1,1,0,5,
        9,0x24,1,0,1,9,0,1,3,
        9,4,3,0,2,1,3,0,5,
        7,0x24,1,0,1,65,0,
        6,0x24,2,1,1,0,6,0x24,2,2,2,0,
        9,0x24,3,1,3,1,2,1,0,9,0x24,3,2,4,1,1,1,0,
        9,5,3,2,64,0,0,0,0,5,0x25,1,1,1,
        9,5,0x83,2,64,0,0,0,0,5,0x25,1,1,3]
    assert len(config)==175
    strings=['F1 FPGA prototype','YM2203 F1 CDC MIDI',None,'F1 control','YM2203 F1 MIDI']
    result={0x0200:bytes(config),0x0300:bytes([4,3,9,4])}
    for i,text in enumerate(strings,1):
        if text is not None:
            b=text.encode('utf-16-le');result[0x0300+i]=bytes([len(b)+2,3])+b
    return result

def render():
    data=descriptors()
    lines=['// SPDX-License-Identifier: MIT','// Generated by tools/usb_descriptors.py; do not edit.',
        'module revc_usb_descriptors #(',"    parameter [15:0] VID=16'h0000,PID=16'h0000,",'    parameter [63:0] SERIAL=0',
        ')(input wire [15:0] key,offset,output reg [7:0] data,output reg [15:0] length,output reg valid);',
        '    always @* begin','        data=0;length=0;valid=1;','        case(key)',
        "            16'h0100: begin",'                length=18;case(offset)']
    dev=[18,1,0,2,0xef,2,1,64,'VID[7:0]','VID[15:8]','PID[7:0]','PID[15:8]',0,1,1,2,"SERIAL!=0 ? 8'd3 : 8'd0",1]
    for i,v in enumerate(dev):lines.append(f"                    16'd{i}:data="+(f"8'd{v}" if isinstance(v,int) else v)+';')
    lines+=['                    default:data=0;endcase','            end',"            16'h0303: begin",'                length=34;case(offset)',"                    16'd0:data=34;16'd1:data=3;"]
    for i in range(16):
        shift=(15-i)*4
        lines.append(f"                    16'd{2+2*i}:data=(4'(SERIAL>>{shift})<10) ? 8'd48+8'(4'(SERIAL>>{shift})) : 8'd55+8'(4'(SERIAL>>{shift}));")
    lines+=['                    default:data=0;endcase','            end']
    for key,b in data.items():
        lines.append(f"            16'h{key:04x}: begin length={len(b)};case(offset)")
        for i,v in enumerate(b):lines.append(f"                16'd{i}:data=8'h{v:02x};")
        lines+=['                default:data=0;endcase','            end']
    lines+=['            default:begin valid=0;length=0;end','        endcase','    end','endmodule','']
    return '\n'.join(lines)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--rtl',type=Path,required=True);a=p.parse_args();a.rtl.write_text(render())
