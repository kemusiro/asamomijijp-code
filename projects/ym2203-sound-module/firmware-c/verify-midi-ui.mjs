// Browser UI with a modelled MIDI output;no physical device or permissions exercised.
import { chromium } from '@playwright/test';
import { fileURLToPath } from 'node:url';
const browser = await chromium.launch({ headless:true });
try {
  const page = await browser.newPage();
  await page.clock.install();
  await page.addInitScript(() => {
    window.sent = [];
    const port = {id:'test',name:'YM2203 Rev C MIDI',state:'connected',open:async()=>{},send:data=>window.sent.push([...data])};
    const access = {outputs:new Map([['test',port]])};
    Object.defineProperty(navigator,'requestMIDIAccess',{value:async()=>access});
  });
  await page.goto(process.argv[2] || 'file://'+fileURLToPath(new URL('pc/usb-midi-test.html',import.meta.url)));
  if (!(await page.locator('#scale').isDisabled())) throw new Error('Playback enabled before selection');
  await page.locator('#connect').click();
  await page.locator('#port').selectOption('test');
  await page.waitForFunction(()=>!document.getElementById('scale').disabled);
  if (await page.evaluate(()=>window.sent.length)) throw new Error('Unrequested MIDI before selection');
  await page.locator('#channel').selectOption('3');
  await page.evaluate(()=>{window.sent=[];});
  await page.locator('#scale').click();
  await page.clock.runFor(8000);
  const sent = await page.evaluate(()=>window.sent);
  const ons = sent.filter(data=>data[0]===0x93);
  const offs = sent.filter(data=>data[0]===0x83);
  if (JSON.stringify(ons.map(data=>data[1]))!=='[60,62,64,65,67,65,64,62,60]' || offs.length!==9) throw new Error('MIDI scale/order/channel mismatch');
  await page.evaluate(()=>{window.sent=[];});
  await page.locator('#scale').click();
  await page.clock.runFor(400);
  await page.locator('#panic').click();
  const afterStop = await page.evaluate(()=>window.sent.length);
  await page.clock.runFor(8000);
  if (await page.evaluate(()=>window.sent.length)!==afterStop) throw new Error('Playback continued after stop');
  const box = await page.locator('#hold').boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();await page.clock.runFor(350);await page.mouse.up();
  const last = await page.evaluate(()=>window.sent.at(-1));
  if (last[0]!==0x83 || last[1]!==60) throw new Error('Held note missing Note Off');
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  const panic = await page.evaluate(()=>window.sent.at(-1));
  if (panic[0]!==0xB0 || panic[1]!==120) throw new Error('Blur did not silence');
  await page.evaluate(()=>{window.sent=[];});
  await page.locator('#six').click();
  await page.clock.runFor(8500);
  const six = await page.evaluate(()=>window.sent.filter(data=>(data[0]&0xF0)===0x90));
  const expectedChord = [[0x90,60,100],[0x91,64,100],[0x92,67,100],[0x93,48,100],[0x94,52,100],[0x95,55,100]];
  if (JSON.stringify(six)!==JSON.stringify([...expectedChord,...expectedChord])) throw new Error('Six solo/chord message mapping mismatch');
  const beforeBlur = await page.evaluate(()=>window.sent.length);
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  if (await page.evaluate(()=>window.sent.length)!==beforeBlur) throw new Error('Handover chord stopped on application switch');
  await page.clock.runFor(120000);
  if ((await page.evaluate(()=>window.sent.at(-1)))[1]!==120) throw new Error('Handover timeout did not silence');
  if (!(await page.locator('#mode').textContent()).startsWith('通常モード')) throw new Error('Holding mode did not clear');
  await page.evaluate(()=>{window.sent=[];});
  await page.locator('#probe').click();
  await page.clock.runFor(15000);
  const probes = await page.evaluate(()=>window.sent.filter(data=>(data[0]&0xF0)===0x90));
  if (probes.length!==18 || probes.slice(0,9).some(data=>data[0]!==0x90) || probes.slice(9).some(data=>data[0]!==0x93)) throw new Error('I2C probe did not send both complete MIDI scales');
  await page.locator('#latch').click();await page.clock.runFor(400);
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();await page.clock.runFor(350);await page.mouse.up();
  if (!(await page.locator('#mode').textContent()).startsWith('通常モード')) throw new Error('Single-note mode did not cancel background hold');
  await page.locator('#latch').click();await page.clock.runFor(400);
  await page.evaluate(()=>window.dispatchEvent(new Event('pagehide')));
  const beforeIdle = await page.evaluate(()=>window.sent.length);
  await page.clock.runFor(120000);
  if (await page.evaluate(()=>window.sent.length)!==beforeIdle) throw new Error('Old hold timer sent more MIDI after page exit');
  console.log('PASS: browser selection/scale/hold/panic,six solo+chord,background handover,2min timeout,two-family probe,normal-mode cancellation and page-exit cleanup;MIDI output modelled');
} finally { await browser.close(); }
