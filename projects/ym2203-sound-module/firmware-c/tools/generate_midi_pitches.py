"""Generate C MIDI pitch tables for the fixed 4MHz YM2203 clock."""
import argparse
from pathlib import Path


def source():
    high, low, periods = [], [], []
    for note in range(128):
        hz = 440.0 * 2.0 ** ((note - 69) / 12.0)
        block = 0
        fnum = round(hz * 144 * 1048576 / 4000000)
        while fnum > 2047 and block < 7:
            block += 1
            fnum = round(hz * 144 * 1048576 / (4000000 * (1 << block)))
        high.append((block << 3) | (fnum >> 8) if fnum <= 2047 else 255)
        low.append(fnum & 255)
        period = round(62500 / hz)
        periods.append(period if 1 <= period <= 4095 else 0)
    text = '// SPDX-License-Identifier: MIT\n// Generated by tools/generate_midi_pitches.py; fixed 4MHz.\n'
    for name, ctype, values in [('midi_high', 'uint8_t', high), ('midi_low', 'uint8_t', low),
                                ('midi_period', 'uint16_t', periods)]:
        text += 'static const ' + ctype + ' ' + name + '[128]={\n'
        for i in range(0, 128, 16):
            text += '    ' + ','.join(str(v) for v in values[i:i + 16]) + ',\n'
        text += '};\n'
    return text


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    path = Path(__file__).resolve().parents[1] / 'src/midi_pitch.h'
    if args.check:
        if path.read_text() != source():
            raise SystemExit('MIDI pitch tables are stale')
        print('PASS: all 128 C MIDI pitch table entries reproduce at 4MHz')
    else:
        path.write_text(source())
