"""Generate checked-in4MHz MIDI tables; --check validates without writing."""
from pathlib import Path
import sys

high=[];low=[];periods=[]
for note in range(128):
    hz=440.0*2.0**((note-69)/12.0)
    block=0
    fnum=round(hz*144*1048576/4000000)
    while fnum>2047 and block<7:
        block+=1
        fnum=round(hz*144*1048576/(4000000*(1<<block)))
    high.append((block<<3)|(fnum>>8) if fnum<=2047 else 255)
    low.append(fnum&255)
    period=round(62500/hz)
    periods.append(period if 1<=period<=4095 else 0)
source='# SPDX-License-Identifier: MIT\n# Generated by generate-midi-pitches.py for the fixed4MHz clock;managed source.\n'
for name,values in (('FM_HIGH',high),('FM_LOW',low),('SSG_PERIODS',periods)):
    source+=name+' = '+('bytes((' if name!='SSG_PERIODS' else '(')+'\n'
    for i in range(0,128,16):source+='    '+','.join(str(v) for v in values[i:i+16])+',\n'
    source+=('))' if name!='SSG_PERIODS' else ')')+'\n'
path=Path(__file__).resolve().parent/'src/ym2203_pitch.py'
if '--check' in sys.argv:
    if path.read_text()!=source:raise SystemExit('MIDI pitch tables are stale')
    print('PASS: all128 MIDI table entries reproduce at4MHz')
else:path.write_text(source)
